for (const [code, overrides] of Object.entries(localePacks)) {
  const base = code === 'zh-TW' ? messages['zh-CN'] : messages['en-US']
  messages[code] = { ...base, ...overrides }
}

const state = reactive({
  locale: localStorage.getItem('nms_locale') || 'zh-CN',
})

export const locale = computed(() => state.locale)

export function setLocale(value) {
  const next = messages[value] ? value : 'zh-CN'
  state.locale = next
  localStorage.setItem('nms_locale', next)
  document.documentElement.lang = next
  document.documentElement.dir = next === 'ar-SA' ? 'rtl' : 'ltr'
}

export function t(key, params) {
  let text = messages[state.locale]?.[key] ?? messages['zh-CN']?.[key] ?? key
  if (params) {
    text = text.replace(/\{(\w+)\}/g, (m, name) =>
      params[name] === undefined ? m : params[name]
    )
  }
  return text
}

